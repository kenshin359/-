async function main() {
  if (!APP) throw new Error('KINTONE_TASK_APP_ID か --app=番号 を指定してください');
  const existing = new Set();
  const r = await call('GET', `/k/v1/records.json?app=${APP}&query=${encodeURIComponent('limit 500')}`);
  for (const rec of r.records ?? []) existing.add(rec.task_name?.value);

  const records = SEED.filter((s) => !existing.has(s[2])).map(
    ([team, tantou, task, done, pri, imp, due, status, yanai]) => ({
      team: { value: team },
      tantou: { value: tantou },
      task_name: { value: task },
      done_def: { value: done },
      priority: { value: pri },
      impact: { value: imp },
      ...(due ? { due: { value: due } } : {}),
      status: { value: status },
      yanai: { value: yanai },
    })
  );
  if (!records.length) {
    console.log('登録済みのため追加なし（重複防止）');
    return;
  }
  for (let i = 0; i < records.length; i += 100) {
    await call('POST', '/k/v1/records.json', { app: APP, records: records.slice(i, i + 100) });
  }
  console.log(`✅ ${records.length}件の初期タスクを登録しました（既存${existing.size}件はスキップ）`);
}

const isMain = process.argv[1] && process.argv[1].endsWith('taskBoardSeed.js');
if (isMain) {
  main().catch((e) => { console.error('エラー:', e.message, JSON.stringify(e.body ?? '')); process.exit(1); });
}
