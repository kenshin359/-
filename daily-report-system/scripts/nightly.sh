#!/bin/sh
# ============================================================
#  毎晩の定時処理（19:00 に自動で動きます）
# ------------------------------------------------------------
#  やること:
#    1. 売上が新しく記載されていれば、分析つきで Chatwork に通知
#    2. 「通知した日付の記録」が増えていたら、記録を残す
#
#  ★2 が必要な理由:
#    定時実行のたびにサーバーが作り直されるため、記録を残さないと
#    同じ日の通知を毎晩くり返してしまいます。
#    記録の中身は日付だけで、売上金額や個人情報は含みません。
#
#  実行:
#    npm run nightly
# ============================================================
set -e
cd "$(dirname "$0")/.."

echo "── 売上の確認 ──"
node scripts/watchSales.js "$@"

# 通知の記録に変化があれば残す（無ければ何もしない）
if [ -n "$(git status --porcelain -- state/notified-sales.json)" ]; then
  echo "── 通知記録の保存 ──"
  git add state/notified-sales.json
  git commit -q -m "売上通知の記録を更新（自動）" || true
  git push -q origin HEAD 2>/dev/null || echo "  （記録の保存に失敗しました。通知自体は送信済みです）"
  echo "  保存しました"
else
  echo "── 新しく通知した日はありません ──"
fi
