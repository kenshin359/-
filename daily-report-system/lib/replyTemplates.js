/** レビューごとに決まる（が、隣どうしでは変わる）番号 */
export function rotationIndex(review) {
  const s = `${review.date}|${review.who}|${String(review.body ?? '').slice(0, 40)}`;
  let h = 0;
  for (const ch of s) h = (h * 31 + ch.codePointAt(0)) % 9973;
  return h;
}

/** 話題を見つける（優先度順・最大2件） */
export function detectThemes(body) {
  const found = [];
  for (const [name, re] of THEME_RULES) {
    if (re.test(body)) found.push(name);
    if (found.length >= 2) break;
  }
  return found;
}

/**
 * AIの出力と同じ形（{body, apology, needs_human, topics}）を
 * テンプレートから作る。assembleReply にそのまま渡せる。
 */
export function draftFromTemplates(review) {
  const body = String(review.body ?? '');
  const idx = rotationIndex(review);
  const themes = detectThemes(body);

  const star = Number(review.star) || 0;
  const negative = star <= 3;

  let personal = '';
  if (!negative) {
    const lines = [];
    const used = themes.length ? themes : ['_一般'];
    for (const t of used.slice(0, 2)) {
      const bank = THEME_LINES[t] ?? THEME_LINES._一般;
      lines.push(bank[idx % bank.length]);
    }
    personal = lines.join('');
  } else {
    // 低評価でも、褒めている部分があれば一言だけ受け止める
    if (themes.length) {
      const bank = THEME_LINES[themes[0]] ?? THEME_LINES._一般;
      personal = bank[idx % bank.length];
    }
  }

  let apology = '';
  if (negative) {
    const hit = APOLOGY_LINES.find(([re]) => re && re.test(body));
    apology = (hit ?? APOLOGY_LINES[APOLOGY_LINES.length - 1])[1];
  }

  return {
    body: personal,
    apology,
    needs_human: star <= 3,
    reason: star <= 3 ? '低評価のため文面の確認が必要' : '',
    topics: themes,
  };
}

/**
 * 低評価（★3以下）用の組み立て。
 * 明るい結び（「これからもたくさんご使用ください」等）は使わず、
 * お詫び → 窓口のご案内 → 再発防止 で締める。
 */
export function assembleNegativeReply(ai, cfg) {
  const b = cfg.blocks;
  const parts = [
    b.greeting,
    b.thanks_feedback ?? 'この度は貴重なご意見をお寄せいただき、誠にありがとうございます。',
  ];
  if ((ai.body ?? '').trim()) parts.push(ai.body.trim());
  if ((ai.apology ?? '').trim()) parts.push(ai.apology.trim());
  parts.push('よろしければ、お手数ですがショップの問い合わせ窓口までご連絡ください。状況を確認のうえ、担当者よりご案内させていただきます。');
  parts.push('いただいたご指摘を真摯に受け止め、同じことが起きないよう改善に努めてまいります。');
  return parts.filter(Boolean).join('\n');
}
